#!/usr/bin/env python3
"""自动生成 traceability matrix（Story × Change × Revision × Rules × Commits × FR）

按 foundations/progress-traceability-and-binding.md §5 与
domains/tooling/progress-binding/_summary.yaml tool.binding.r5。

输出：
  - markdown matrix 表（默认 STDOUT 或 --report 指定路径）
  - 覆盖率统计 + drift 一览

用法:
  python scripts/gen_progress_matrix.py --report _logs/progress-matrix.md
  python scripts/gen_progress_matrix.py --report _logs/progress-matrix.md --include-archived
"""
from __future__ import annotations

import argparse
import datetime as dt
import subprocess
import sys
from pathlib import Path

# 复用 check_progress_consistency.py 的采集器（其 YAML 解析经 _governance_yaml
# 已零依赖化：缺 pyyaml 也能跑；缺 .git 时下方 git_* 调用各自优雅降级）。
sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_progress_consistency import (  # noqa: E402
    collect_changes, collect_revisions, collect_rule_definitions, collect_stories,
    collect_revisions_index, repo_root,
)


def git_short_log(root: Path, n: int = 5) -> list[str]:
    try:
        out = subprocess.run(
            ["git", "log", f"-{n}", "--oneline", "--no-decorate"],
            cwd=root, capture_output=True, text=True, check=False, encoding="utf-8",
        )
        return [line for line in (out.stdout or "").splitlines() if line.strip()]
    except Exception:
        return []


def find_commits_for_id(root: Path, *ids: str) -> list[str]:
    commits: list[str] = []
    for ident in ids:
        if not ident:
            continue
        try:
            out = subprocess.run(
                ["git", "log", "--all", "--pretty=%h", "--grep", ident, "-50"],
                cwd=root, capture_output=True, text=True, check=False, encoding="utf-8",
            )
            commits.extend(line.strip() for line in (out.stdout or "").splitlines() if line.strip())
        except Exception:
            pass
    seen, ordered = set(), []
    for c in commits:
        if c not in seen:
            seen.add(c)
            ordered.append(c)
    return ordered


def render_matrix(root: Path, include_archived: bool) -> str:
    stories = collect_stories(root)
    changes = collect_changes(root)
    revisions = collect_revisions(root)
    rules = collect_rule_definitions(root)
    idx_revisions = collect_revisions_index(root) or []

    if not include_archived:
        revisions = [r for r in revisions if "archived" not in (r.get("__form") or "")]
        changes = [c for c in changes if not c.get("__archived")]

    change_by_id = {c.get("change_id"): c for c in changes if c.get("change_id")}
    revision_by_id = {r.get("revision_id"): r for r in revisions if r.get("revision_id")}

    out = [
        f"# Traceability Matrix — auto-generated {dt.datetime.now(dt.timezone.utc).isoformat()}",
        "",
        "> Source of truth: BMAD `_bmad/<project>/stories/`, OpenSpec `openspec/changes/`, ",
        "> Revisions `revisions/`, Rules `domains/**/_summary.yaml`. Generated by `scripts/gen_progress_matrix.py`.",
        "",
    ]

    # ─── 覆盖率 ───
    out.append("## Overview")
    out.append("")
    out.append(f"- BMAD stories: **{len(stories)}**")
    out.append(f"- OpenSpec changes (live): **{len(changes)}**")
    out.append(f"- Revisions (live): **{len(revisions)}**")
    out.append(f"- Rules with rule_id: **{len(rules)}**")
    out.append(f"- revisions/index.yaml entries: **{len(idx_revisions)}**")
    out.append("")

    # ─── Stories matrix ───
    out.append("## Stories")
    out.append("")
    if not stories:
        out.append("_No BMAD stories yet (BMAD layer not in use for this project)._")
    else:
        out.append("| Story | Status | PRD | Change | Change Status | Revision | Rev Status | Last Commit |")
        out.append("|-------|--------|-----|--------|---------------|----------|-----------|-------------|")
        for s in stories:
            sid = s.get("story_id", "?")
            st = s.get("status", "—")
            prd = ", ".join(s.get("prd_refs") or []) or "—"
            lc = s.get("linked_change") or "—"
            c_st = "—"
            if lc != "—" and lc in change_by_id:
                c_st = change_by_id[lc].get("status") or "—"
            lr = s.get("linked_revision") or "—"
            r_st = "—"
            if lr != "—" and lr in revision_by_id:
                r_st = revision_by_id[lr].get("status") or "—"
            commits = find_commits_for_id(root, sid)
            last_commit = commits[0] if commits else "—"
            out.append(f"| `{sid}` | {st} | {prd} | `{lc}` | {c_st} | `{lr}` | {r_st} | {last_commit} |")
    out.append("")

    # ─── Revisions matrix ───
    out.append("## Revisions")
    out.append("")
    if not revisions:
        out.append("_No revisions found._")
    else:
        out.append("| Revision | Status | Stories | Changes | Introduces Rules | Path |")
        out.append("|----------|--------|---------|---------|------------------|------|")
        for r in revisions:
            rid = r.get("revision_id", "?")
            st = r.get("status") or r.get("__form") or "—"
            ls = ", ".join(r.get("linked_stories") or []) or "—"
            lc = ", ".join(r.get("linked_changes") or []) or "—"
            ir = ", ".join(r.get("introduces_rules") or []) or "—"
            path = r.get("__path", "—")
            out.append(f"| `{rid}` | {st} | {ls} | {lc} | {ir} | `{path}` |")
    out.append("")

    # ─── Changes matrix ───
    out.append("## OpenSpec Changes")
    out.append("")
    if not changes:
        out.append("_No live OpenSpec changes._")
    else:
        out.append("| Change | Status | Linked Story | Linked Revision | Path |")
        out.append("|--------|--------|--------------|-----------------|------|")
        for c in changes:
            cid = c.get("change_id", "?")
            st = c.get("status", "—")
            ls = c.get("linked_story") or "—"
            lr = c.get("linked_revision") or "—"
            path = c.get("__path", "—")
            out.append(f"| `{cid}` | {st} | `{ls}` | `{lr}` | `{path}` |")
    out.append("")

    # ─── Rules ↔ Revision ───
    out.append("## Rules introduced by Revisions")
    out.append("")
    if not rules:
        out.append("_No rules with rule_id found._")
    else:
        rule_by_rev: dict[str, list[tuple[str, str]]] = {}
        for rid, rel, rule in rules:
            ib = rule.get("introduced_by") or "—"
            rule_by_rev.setdefault(ib, []).append((rid, rel))
        out.append("| Revision (introduced_by) | Rules | Source |")
        out.append("|--------------------------|-------|--------|")
        for ib in sorted(rule_by_rev.keys()):
            rids = ", ".join(f"`{r}`" for r, _ in rule_by_rev[ib])
            sources = ", ".join(sorted({rel for _, rel in rule_by_rev[ib]}))
            out.append(f"| `{ib}` | {rids} | {sources} |")
    out.append("")

    out.append("## Recent commits (top 5)")
    out.append("")
    for line in git_short_log(root, 5):
        out.append(f"- `{line}`")
    out.append("")

    return "\n".join(out)


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--governance-root", default=".")
    p.add_argument("--report", default=None)
    p.add_argument("--include-archived", action="store_true")
    args = p.parse_args(argv)

    root = repo_root(args.governance_root)
    matrix = render_matrix(root, args.include_archived)

    if args.report:
        out = root / args.report
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(matrix, encoding="utf-8")
        print(f"report: {out}")
    else:
        sys.stdout.write(matrix)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
